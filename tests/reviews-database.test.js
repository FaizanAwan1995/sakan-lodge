import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const STAFF='00000000-0000-4000-8000-000000000001';
const OTHER='00000000-0000-4000-8000-000000000002';
const fingerprint='a'.repeat(64);
const payload={display_name:'Real resident',email:'guest@example.test',rating:4,review:'A comfortable stay and helpful team throughout my time here.',suburb:'Fulham',consent:true};
test('testimonial submission, private moderation, public projection and abuse limits',async()=>{
 const db=new PGlite();
 try {
  await db.exec(await readFile(new URL('./database/foundation.sql',import.meta.url),'utf8'));
  await db.exec(`create table public.audit(id bigserial primary key,"by" text,action text);create function public.is_sakan_staff() returns boolean language sql stable as $$select auth.uid()='${STAFF}'::uuid$$;`);
  await db.exec(await readFile(new URL('../supabase/migrations/20261019080417_tenant_testimonials.sql',import.meta.url),'utf8'));
  const role=async(name,uid='')=>{await db.exec(`reset role;set role ${name}`);await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid]);};
  const rpc=async(name,args=[])=> (await db.query(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')}) as result`,args.map(x=>x&&typeof x==='object'?JSON.stringify(x):x))).rows[0].result;
  await role('anon');assert.deepEqual(await rpc('published_testimonials'),[]);
  await assert.rejects(()=>rpc('submit_testimonial',[payload,crypto.randomUUID(),fingerprint]),/permission denied/);
  await assert.rejects(()=>rpc('staff_testimonials',['all']),/permission denied/);
  await assert.rejects(()=>db.query('select * from sakan_reviews.testimonials'),/permission denied/);
  await role('service_role');const key=crypto.randomUUID();
  assert.equal((await rpc('submit_testimonial',[payload,key,fingerprint])).received,true);
  assert.equal((await rpc('submit_testimonial',[payload,key,fingerprint])).received,true);
  await assert.rejects(()=>rpc('submit_testimonial',[{...payload,rating:5},key,fingerprint]),/Request changed/);
  await assert.rejects(()=>rpc('submit_testimonial',[{...payload,consent:false},crypto.randomUUID(),fingerprint]),/Invalid review/);
  await assert.rejects(()=>rpc('submit_testimonial',[{...payload,rating:6},crypto.randomUUID(),fingerprint]),/Invalid review/);
  await assert.rejects(()=>rpc('submit_testimonial',[payload,crypto.randomUUID(),fingerprint]),/limit reached/);
  await role('anon');assert.deepEqual(await rpc('published_testimonials'),[]);
  await role('authenticated',OTHER);
  await assert.rejects(()=>rpc('staff_testimonials',['all']),/Staff access required/);
  await role('authenticated',STAFF);
  const list=await rpc('staff_testimonials',['pending']);assert.equal(list.length,1);assert.equal(list[0].email,payload.email);
  const id=list[0].id;
  await assert.rejects(()=>rpc('moderate_testimonial',[id,1,'published',false]),/Confirm this was a resident/);
  await rpc('moderate_testimonial',[id,1,'published',true]);
  await assert.rejects(()=>rpc('moderate_testimonial',[id,1,'hidden',false]),/Review changed/);
  await role('anon');const published=await rpc('published_testimonials');assert.equal(published.length,1);assert.equal(published[0].rating,4);
  for(const privateKey of ['email','fingerprint','request_key','moderated_by','consent'])assert.equal(privateKey in published[0],false);
  await role('authenticated',OTHER);await assert.rejects(()=>rpc('moderate_testimonial',[id,2,'hidden',false]),/Staff access required/);
  await role('authenticated',STAFF);await rpc('moderate_testimonial',[id,2,'hidden',false]);
  await role('anon');assert.deepEqual(await rpc('published_testimonials'),[]);
  await role('authenticated',STAFF);await rpc('moderate_testimonial',[id,3,'rejected',false]);
  await role('anon');assert.deepEqual(await rpc('published_testimonials'),[]);
  await role('service_role');
  for(let i=0;i<5;i++)await rpc('submit_testimonial',[{...payload,email:`guest${i}@example.test`},crypto.randomUUID(),'b'.repeat(64)]);
  await assert.rejects(()=>rpc('submit_testimonial',[{...payload,email:'another@example.test'},crypto.randomUUID(),'b'.repeat(64)]),/limit reached/);
  await db.exec('reset role');assert.equal((await db.query('select count(*)::int n from public.audit')).rows[0].n,3);
 }finally{await db.close();}
});
